#!/usr/bin/env python3
"""Validate Home Assistant app options and generate managed config files.

This script is run once at every app start (s6 oneshot ``init-khaos``).
It never overwrites files the user owns:

* ``printer.cfg`` and ``moonraker.conf`` are *seeded* only if missing.
* Printer profiles are seeded only if missing; pristine reference copies are
  refreshed under ``klipper-haos/dist/`` so users can diff after updates.
* Files under ``klipper-haos/`` (except ``dist/``) are regenerated on every
  start and must not be edited by hand.

It is deliberately dependency-free (stdlib only) so it can be unit tested
outside the container.
"""

from __future__ import annotations

import argparse
import ipaddress
import json
import os
import re
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path

# The Supervisor ingress proxy. Requests from this address were already
# authenticated by Home Assistant.
INGRESS_PROXY = "172.30.32.2"
# nginx inside the container (Moonraker's direct upstream).
LOCAL_PROXY = "127.0.0.1"
# Home Assistant's internal Docker network. Trusting any part of it would
# trust Home Assistant Core and every other app on the host.
HASSIO_NETWORK = ipaddress.ip_network("172.30.32.0/23")
# Smallest prefix accepted for trusted networks. Wider ranges are almost
# certainly a mistake ("trust everything") rather than a home LAN.
MIN_PREFIX_V4 = 16
MIN_PREFIX_V6 = 48

SERIAL_RE = re.compile(r"^/dev/[A-Za-z0-9._:+/-]+$")
CORS_RE = re.compile(r"^https?://[A-Za-z0-9*.-]+(:[0-9]{1,5})?$")

GENERATED_HEADER = """\
# -----------------------------------------------------------------------------
# GENERATED by the Klipper HAOS app at every start. DO NOT EDIT - changes are
# overwritten. Change the app options in Home Assistant instead, or override
# individual settings in your own config file *after* the include line.
# -----------------------------------------------------------------------------
"""

KLIPPER_INCLUDE = "[include klipper-haos/generated.cfg]"
MOONRAKER_INCLUDE = "[include klipper-haos/moonraker-generated.conf]"


class OptionsError(ValueError):
    """Raised when user-supplied options are invalid or unsafe."""


@dataclass
class Paths:
    config: Path  # user-visible app config folder (/config)
    data: Path  # Moonraker data path (/data/printer_data)
    run: Path  # runtime directory (sockets, pty)
    share: Path  # read-only defaults shipped in the image
    mainsail_config: Path  # mainsail-config checkout

    @property
    def managed(self) -> Path:
        return self.config / "klipper-haos"


@dataclass
class Options:
    serial_device: str | None = None
    trusted_networks: list[str] = field(default_factory=list)
    cors_domains: list[str] = field(default_factory=list)
    export_api_key: bool = False
    log_level: str = "info"


# --------------------------------------------------------------------------
# Validation
# --------------------------------------------------------------------------


def validate_serial(value: object) -> str | None:
    if value in (None, ""):
        return None
    if not isinstance(value, str) or not SERIAL_RE.match(value):
        raise OptionsError(
            f"serial_device {value!r} is not a valid device path "
            "(expected something like /dev/serial/by-id/usb-...)"
        )
    if "/../" in value or value.endswith("/.."):
        raise OptionsError("serial_device must not contain '..'")
    return value


def validate_trusted_networks(values: object) -> list[str]:
    if values is None:
        return []
    if not isinstance(values, list):
        raise OptionsError("trusted_networks must be a list")
    result: list[str] = []
    for raw in values:
        if not isinstance(raw, str):
            raise OptionsError(f"trusted_networks entry {raw!r} is not a string")
        try:
            net = ipaddress.ip_network(raw.strip(), strict=False)
        except ValueError as err:
            raise OptionsError(f"trusted_networks entry {raw!r}: {err}") from err
        min_prefix = MIN_PREFIX_V4 if net.version == 4 else MIN_PREFIX_V6
        if net.prefixlen < min_prefix:
            raise OptionsError(
                f"trusted_networks entry {raw!r} is too broad; "
                f"use a prefix of /{min_prefix} or longer"
            )
        if net.version == 4 and net.overlaps(HASSIO_NETWORK):
            raise OptionsError(
                f"trusted_networks entry {raw!r} overlaps the Home Assistant "
                f"internal network {HASSIO_NETWORK}; this is not allowed"
            )
        if net.is_loopback or net.is_unspecified or net.is_multicast:
            raise OptionsError(f"trusted_networks entry {raw!r} is not allowed")
        if str(net) not in result:
            result.append(str(net))
    return result


def validate_cors(values: object) -> list[str]:
    if values is None:
        return []
    if not isinstance(values, list):
        raise OptionsError("cors_domains must be a list")
    result: list[str] = []
    for raw in values:
        if not isinstance(raw, str) or not CORS_RE.match(raw):
            raise OptionsError(
                f"cors_domains entry {raw!r} must look like http://host[:port]"
            )
        host = raw.split("://", 1)[1].split(":", 1)[0]
        labels = host.split(".")
        # Moonraker rejects wildcards in the top-level domain; so do we, and
        # we also refuse a bare "*" which would allow every origin.
        if host == "*" or "*" in labels[-1]:
            raise OptionsError(f"cors_domains entry {raw!r} is too permissive")
        if raw not in result:
            result.append(raw)
    return result


def parse_options(raw: dict) -> Options:
    if not isinstance(raw, dict):
        raise OptionsError("options must be a JSON object")
    level = raw.get("log_level", "info")
    if level not in ("debug", "info", "warning", "error"):
        raise OptionsError(f"log_level {level!r} is not supported")
    return Options(
        serial_device=validate_serial(raw.get("serial_device")),
        trusted_networks=validate_trusted_networks(raw.get("trusted_networks")),
        cors_domains=validate_cors(raw.get("cors_domains")),
        export_api_key=bool(raw.get("export_api_key", False)),
        log_level=level,
    )


# --------------------------------------------------------------------------
# Rendering
# --------------------------------------------------------------------------


def render_klipper_generated(opts: Options, paths: Paths) -> str:
    lines = [
        GENERATED_HEADER,
        "# Your printer.cfg must contain this line at the very top:",
        f"#   {KLIPPER_INCLUDE}",
        "",
        "# Mainsail client macros (PAUSE, RESUME, CANCEL_PRINT, ...).",
        "[include mainsail.cfg]",
        "",
        "[virtual_sdcard]",
        f"path: {paths.data / 'gcodes'}",
        "on_error_gcode: CANCEL_PRINT",
        "",
    ]
    if opts.serial_device:
        lines += [
            "[mcu]",
            "# From the app option 'serial_device'.",
            f"serial: {opts.serial_device}",
            "",
        ]
    else:
        lines += [
            "# No 'serial_device' is configured in the app options, so no MCU",
            "# serial port is set here. Klipper will report a configuration",
            "# error until you select the printer's serial device.",
            "",
        ]
    return "\n".join(lines)


def render_moonraker_generated(opts: Options, paths: Paths) -> str:
    trusted = [LOCAL_PROXY + "/32", INGRESS_PROXY + "/32", *opts.trusted_networks]
    lines = [
        GENERATED_HEADER,
        "# Your moonraker.conf must contain this line at the very top:",
        f"#   {MOONRAKER_INCLUDE}",
        "",
        "[server]",
        "# Moonraker only listens inside the container (127.0.0.1:7126). nginx is the",
        "# single entry point (ingress on 8099, optional direct port on 7125) and",
        "# always overwrites X-Real-IP, so client addresses cannot be spoofed.",
        "host: 127.0.0.1",
        "port: 7126",
        f"klippy_uds_address: {paths.run / 'klippy.sock'}",
        "max_upload_size: 1024",
        "",
        "[machine]",
        "# Services are supervised by s6-overlay, not systemd.",
        "provider: none",
        "validate_service: False",
        "validate_config: False",
        "",
        "[file_manager]",
        "check_klipper_config_path: False",
        "",
        "[authorization]",
        "# 127.0.0.1: nginx inside this container. Moonraker requires the",
        "#   reverse proxy itself to be trusted; the trust decision for a",
        "#   proxied request is still made on the real client address that",
        "#   nginx forwards. Nothing outside the container can reach 127.0.0.1.",
        "# 172.30.32.2: the Supervisor ingress proxy; these users were already",
        "#   authenticated by Home Assistant.",
        "# Everything else needs an API key or a Moonraker login unless listed",
        "# in the app option 'trusted_networks'.",
        "trusted_clients:",
        *[f"    {t}" for t in trusted],
    ]
    if opts.cors_domains:
        lines += ["cors_domains:", *[f"    {c}" for c in opts.cors_domains]]
    lines += [
        "",
        "[history]",
        "",
        "[octoprint_compat]",
        "",
    ]
    return "\n".join(lines)


# --------------------------------------------------------------------------
# File helpers
# --------------------------------------------------------------------------


def write_if_changed(path: Path, content: str, mode: int = 0o644) -> bool:
    """Write ``content`` only if it differs, to avoid needless disk writes."""
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        if path.read_text(encoding="utf-8") == content:
            return False
    except FileNotFoundError:
        pass
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    os.chmod(tmp, mode)
    os.replace(tmp, path)
    return True


def copy_if_missing(src: Path, dst: Path) -> bool:
    if dst.exists():
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dst)
    return True


def sync_tree(src: Path, dst: Path) -> list[str]:
    """Mirror ``src`` into ``dst`` (overwrite changed files, keep others)."""
    changed = []
    for file in sorted(p for p in src.rglob("*") if p.is_file()):
        rel = file.relative_to(src)
        if write_if_changed(dst / rel, file.read_text(encoding="utf-8")):
            changed.append(str(rel))
    return changed


def has_include(path: Path, include: str) -> bool:
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return False
    return any(line.strip() == include for line in text.splitlines())


# --------------------------------------------------------------------------
# Main entry points
# --------------------------------------------------------------------------


def generate(opts: Options, paths: Paths) -> list[str]:
    """Create/refresh all managed files. Returns human-readable messages."""
    msgs: list[str] = []
    for sub in ("gcodes", "logs", "database", "comms", "misc", "backup", "certs"):
        (paths.data / sub).mkdir(parents=True, exist_ok=True)
    paths.run.mkdir(parents=True, exist_ok=True)

    # Moonraker expects <data>/config; point it at the user-visible folder.
    link = paths.data / "config"
    if link.is_symlink():
        if os.readlink(link) != str(paths.config):
            link.unlink()
            link.symlink_to(paths.config, target_is_directory=True)
    elif link.exists():
        raise OptionsError(
            f"{link} exists and is not a symlink; expected a link to {paths.config}"
        )
    else:
        link.symlink_to(paths.config, target_is_directory=True)

    defaults = paths.share / "defaults"
    if copy_if_missing(defaults / "printer.cfg", paths.config / "printer.cfg"):
        msgs.append("Created starter printer.cfg (inert: no motion, no heaters)")
    if copy_if_missing(defaults / "moonraker.conf", paths.config / "moonraker.conf"):
        msgs.append("Created moonraker.conf")

    profiles = paths.share / "profiles"
    if profiles.is_dir():
        for profile in sorted(p for p in profiles.iterdir() if p.is_dir()):
            for file in sorted(p for p in profile.rglob("*") if p.is_file()):
                rel = file.relative_to(profiles)
                if copy_if_missing(file, paths.config / "profiles" / rel):
                    msgs.append(f"Installed profile file profiles/{rel}")
        sync_tree(profiles, paths.managed / "dist" / "profiles")

    client_cfg = paths.mainsail_config / "client.cfg"
    if client_cfg.is_file():
        write_if_changed(
            paths.managed / "mainsail.cfg",
            client_cfg.read_text(encoding="utf-8"),
        )

    if write_if_changed(
        paths.managed / "generated.cfg", render_klipper_generated(opts, paths)
    ):
        msgs.append("Updated klipper-haos/generated.cfg")
    if write_if_changed(
        paths.managed / "moonraker-generated.conf",
        render_moonraker_generated(opts, paths),
    ):
        msgs.append("Updated klipper-haos/moonraker-generated.conf")

    if not has_include(paths.config / "printer.cfg", KLIPPER_INCLUDE):
        msgs.append(
            f"WARNING: printer.cfg does not contain '{KLIPPER_INCLUDE}'. "
            "The serial device and G-code path from the app will not be used."
        )
    if not has_include(paths.config / "moonraker.conf", MOONRAKER_INCLUDE):
        msgs.append(
            f"WARNING: moonraker.conf does not contain '{MOONRAKER_INCLUDE}'. "
            "Moonraker will not be configured for this app and may not work."
        )
    return msgs


def default_paths() -> Paths:
    env = os.environ.get
    return Paths(
        config=Path(env("KHAOS_CONFIG_DIR", "/config")),
        data=Path(env("KHAOS_DATA_DIR", "/data/printer_data")),
        run=Path(env("KHAOS_RUN_DIR", "/run/klipper-haos")),
        share=Path(env("KHAOS_SHARE_DIR", "/usr/share/klipper-haos")),
        mainsail_config=Path(env("KHAOS_MAINSAIL_CONFIG_DIR", "/opt/mainsail-config")),
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["validate", "generate"])
    parser.add_argument("--options", default="/data/options.json")
    args = parser.parse_args(argv)

    try:
        with open(args.options, encoding="utf-8") as fh:
            raw = json.load(fh)
        opts = parse_options(raw)
        if args.command == "generate":
            for msg in generate(opts, default_paths()):
                print(msg)
    except (OptionsError, OSError, json.JSONDecodeError) as err:
        print(f"ERROR: {err}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
