#!/usr/bin/env python3
"""Write a small G-code file with an embedded PNG thumbnail (PrusaSlicer
style) for the integration tests. Stdlib only."""

import base64
import struct
import sys
import zlib


def png(width: int, height: int) -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))

    # Scanlines: filter byte 0 followed by RGB pixels (a simple gradient).
    raw = b"".join(
        b"\x00" + b"".join(bytes((x * 255 // width, y * 255 // height, 128)) for x in range(width))
        for y in range(height)
    )
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def main(path: str) -> None:
    data = base64.b64encode(png(300, 300)).decode()
    lines = [data[i:i + 78] for i in range(0, len(data), 78)]
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("; generated by PrusaSlicer 2.8.1+linux-x64 on 2026-11-10 at 12:00:00 UTC\n\n")
        fh.write(f"; thumbnail begin 300x300 {len(data)}\n")
        for line in lines:
            fh.write(f"; {line}\n")
        fh.write("; thumbnail end\n\n")
        fh.write("G28\nG1 X10 Y10 Z0.3 F3000\nG1 X50 E2\n")
        fh.write("; estimated printing time (normal mode) = 1m 2s\n")
        fh.write("; filament used [mm] = 2.00\n")


if __name__ == "__main__":
    main(sys.argv[1])
